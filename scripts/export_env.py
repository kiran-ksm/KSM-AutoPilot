#!/usr/bin/env python3
"""
export_env.py — Read CDK stack outputs and write frontend + backend .env files.

Usage:
    python scripts/export_env.py --env dev
    python scripts/export_env.py --env staging
    python scripts/export_env.py --env prod

Requires AWS CLI configured with credentials that can call
`cloudformation describe-stacks` in the target account/region.

What it does:
1. Reads outputs from KsmAp-<env>-Foundation, KsmAp-<env>-Database, KsmAp-<env>-Api, KsmAp-<env>-Ai
2. Writes frontend/.env.<env>.local  (gitignored — safe to contain real values)
3. Writes backend/.env.<env>.local   (gitignored)
4. Prints a summary — never logs secret values to stdout
"""

import argparse
import subprocess
import json
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent


def get_stack_outputs(stack_name: str) -> dict[str, str]:
    result = subprocess.run(
        ["aws", "cloudformation", "describe-stacks", "--stack-name", stack_name],
        capture_output=True, text=True
    )
    if result.returncode != 0:
        print(f"  WARNING: Could not read stack {stack_name}: {result.stderr.strip()}")
        return {}
    data = json.loads(result.stdout)
    stacks = data.get("Stacks", [])
    if not stacks:
        return {}
    return {o["OutputKey"]: o["OutputValue"] for o in stacks[0].get("Outputs", [])}


def write_env_file(path: Path, values: dict[str, str]) -> None:
    lines = [f"# Auto-generated by scripts/export_env.py — DO NOT COMMIT\n"]
    for k, v in values.items():
        lines.append(f"{k}={v}\n")
    path.write_text("".join(lines))
    print(f"  Written: {path.relative_to(ROOT)}")


def main():
    parser = argparse.ArgumentParser(description="Export CDK outputs to .env files")
    parser.add_argument("--env", required=True, choices=["dev", "staging", "prod"])
    parser.add_argument("--region", default="us-east-1")
    args = parser.parse_args()
    env = args.env
    prefix = f"KsmAp-{env}"

    print(f"\nReading CDK outputs for environment: {env}\n")

    foundation = get_stack_outputs(f"{prefix}-Foundation")
    database   = get_stack_outputs(f"{prefix}-Database")
    api        = get_stack_outputs(f"{prefix}-Api")
    ai         = get_stack_outputs(f"{prefix}-Ai")

    if not foundation:
        print("ERROR: Foundation stack outputs not found. Has the stack been deployed?")
        sys.exit(1)

    dist_domain = foundation.get("DistributionDomain", "")
    api_url     = api.get("ApiUrl", "").rstrip("/") + "/api/v1"
    user_pool   = foundation.get("UserPoolId", "")
    client_id   = foundation.get("UserPoolClientId", "")
    table_name  = database.get("TableName", "")
    guardrail   = ai.get("GuardrailId", "")

    # ── Frontend .env.<env>.local ─────────────────────────────────────────────
    frontend_env = {
        "VITE_AWS_REGION":            args.region,
        "VITE_COGNITO_USER_POOL_ID":  user_pool,
        "VITE_COGNITO_CLIENT_ID":     client_id,
        "VITE_API_BASE_URL":          api_url,
        "VITE_DEMO_MODE":             "true" if env != "prod" else "false",
        "VITE_APP_ENV":               env,
    }
    write_env_file(ROOT / "frontend" / f".env.{env}.local", frontend_env)

    # ── Backend .env.<env>.local ──────────────────────────────────────────────
    backend_env = {
        "AWS_REGION":                args.region,
        "DYNAMODB_TABLE_NAME":       table_name,
        "DYNAMODB_GSI1_NAME":        "GSI1",
        "DEMO_MODE":                 "true" if env != "prod" else "false",
        "BEDROCK_MODEL_ID":          "anthropic.claude-3-sonnet-20240229-v1:0",
        "BEDROCK_GUARDRAIL_ID":      guardrail,
        "BEDROCK_GUARDRAIL_VERSION": "DRAFT",
        "ALLOWED_ORIGIN":            dist_domain,
        "POWERTOOLS_SERVICE_NAME":   f"ksmap-{env}",
        "LOG_LEVEL":                 "DEBUG" if env == "dev" else "INFO",
        "SKIP_AUTH_VERIFY":          "true" if env == "dev" else "false",
    }
    write_env_file(ROOT / "backend" / f".env.{env}.local", backend_env)

    print(f"\nDone. Add these files to .gitignore if not already present.")
    print(f"Summary (keys only — values omitted):")
    for k in frontend_env:
        print(f"  frontend: {k}")
    for k in backend_env:
        print(f"  backend:  {k}")


if __name__ == "__main__":
    main()
